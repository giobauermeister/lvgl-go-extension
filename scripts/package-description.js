// Generate a self-contained extension listing from the GitHub README and user
// guides. Relative documentation links do not resolve in every extension host.
const fs = require('node:fs');
const path = require('node:path');
const MarkdownIt = require('markdown-it');
const root = path.resolve(__dirname, '..');
const repository = require('../package.json').repository.url.replace(/\.git$/, '');
const imageBase = repository.replace('https://github.com/', 'https://raw.githubusercontent.com/') + '/main/';
const topics = [
  ['configuration', 'Project configuration'],
  ['hardware-frames', 'Hardware frames'],
  ['memory', 'Memory monitor'],
  ['sharing', 'Share an HTML preview'],
  ['hosting', 'PWA hosting (advanced)']
];
const styles = {
  p: 'margin:0 0 14px;line-height:1.7',
  h1: 'font-size:24px;line-height:1.35;margin:0 0 14px;padding:0;border:0',
  h2: 'font-size:18px;line-height:1.4;margin:28px 0 12px',
  h3: 'font-size:15px;line-height:1.4;margin:22px 0 10px',
  ol: 'margin:0 0 16px;padding-left:24px',
  ul: 'margin:0 0 16px;padding-left:22px',
  li: 'margin:0 0 8px;line-height:1.7',
  table: 'border-collapse:collapse;width:100%;margin:0 0 18px;line-height:1.6',
  th: 'padding:10px;text-align:left;border-bottom:1px solid #777',
  td: 'padding:10px;vertical-align:top;border-bottom:1px solid #777',
  code: 'font-family:monospace;font-size:.95em',
  pre: 'padding:14px;line-height:1.6;overflow:auto;border:1px solid #777;border-radius:6px;margin:0 0 18px'
};

function render(source, nested = false) {
  const md = new MarkdownIt();
  const tokens = md.parse(source, {});
  for (const token of tokens) {
    if (nested && token.tag === 'h2') token.tag = 'h3';
    if (token.nesting !== -1 && styles[token.tag]) token.attrSet('style', styles[token.tag]);
    for (const child of token.children ?? []) {
      if (child.nesting !== -1 && styles[child.tag]) child.attrSet('style', styles[child.tag]);
      if (child.type === 'image') {
        const source = child.attrGet('src');
        if (source && !/^https:\/\//.test(source)) {
          if (!fs.existsSync(path.join(root, source))) throw new Error(`Missing description image: ${source}`);
          child.attrSet('src', new URL(source, imageBase).href);
        }
        child.attrSet('style', 'max-width:100%;height:auto');
      }
      if (child.type !== 'link_open') continue;
      const href = child.attrGet('href');
      const name = href?.match(/(?:^|\/)([^/]+)\.md$/)?.[1];
      if (topics.some(([id]) => id === name)) child.attrSet('href', '#lvgl-go-' + name);
      else if (href && !/^(https:\/\/|#)/.test(href)) throw new Error(`Unresolved description link: ${href}`);
    }
  }
  // Hide the complete title line, including its inline content.
  if (nested) tokens.splice(0, 3);
  md.renderer.rules.fence = (tokens, index) => `<pre style="${styles.pre}"><code>${md.utils.escapeHtml(tokens[index].content)}</code></pre>\n`;
  return md.renderer.render(tokens, md.options, {});
}

const readme = fs.readFileSync(path.join(root, 'README.md'), 'utf8');
const documentation = readme.indexOf('\n## Documentation\n');
if (documentation < 0) throw new Error('README.md must have a Documentation section after the shared introduction.');
const intro = readme.slice(0, documentation);
let html = '<!-- Generated by npm run docs from README.md and docs/*.md. -->\n';
html += '<div style="max-width:820px;font-size:14px;line-height:1.7;padding:16px 0 28px">\n';
html += render(intro);
html += '<h2 style="' + styles.h2 + '">More information</h2>\n';
html += '<p style="' + styles.p + '">Expand a topic to read it here.</p>\n';
for (const [id, title] of topics) {
  const source = fs.readFileSync(path.join(root, 'docs', id + '.md'), 'utf8');
  html += `<details id="lvgl-go-${id}" style="margin:0 0 12px;padding:12px 0;border-top:1px solid #777">\n`;
  html += `<summary style="cursor:pointer;font-size:15px;font-weight:600;line-height:1.6">${title}</summary>\n`;
  html += '<div style="padding:18px 0 6px">\n' + render(source, true) + '</div>\n</details>\n';
}
html += '</div>\n';
const output = path.join(root, 'artifacts', 'extension-readme.md');
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, html);
console.log('Generated the formatted, self-contained extension description.');
