// Render every icon from media/icon.svg. Requires Inkscape only when editing artwork.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { startupImages } = require('./startup-images');
const media = path.join(__dirname, '..', 'media');
const source = fs.readFileSync(path.join(media, 'icon.svg'), 'utf8');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'lvgl-go-icons-'));
try {
  const render = (input, output, width, height = width) => execFileSync(process.env.INKSCAPE ?? 'inkscape', [input,
    '--export-type=png', `--export-width=${width}`, `--export-height=${height}`, `--export-filename=${output}`],
    { env: { ...process.env, XDG_CACHE_HOME: temporary }, stdio: ['ignore', 'pipe', 'pipe'] });
  for (const size of [180, 192, 512]) render(path.join(media, 'icon.svg'), path.join(media, `icon-${size}.png`), size);
  // Keep the extension-list icon at the package root for host asset compatibility.
  render(path.join(media, 'icon.svg'), path.join(media, '..', 'icon.png'), 128);
  // A fully opaque background for Android's adaptive icon masks; same phone artwork.
  const maskable = path.join(temporary, 'maskable.svg');
  fs.writeFileSync(maskable, source.replace('rx="104"', 'rx="0"').replace('<g id="phone">', '<g id="phone" transform="translate(256 256) scale(.9) translate(-256 -256)">'));
  render(maskable, path.join(media, 'icon-maskable-512.png'), 512);
  // Crop to the phone bounds so it fills the Activity Bar icon slot.
  // Keep a small margin for the outer curve and the editor foreground color.
  fs.writeFileSync(path.join(media, 'activity.svg'), source
    .replace('width="512" height="512" viewBox="0 0 512 512"', 'width="24" height="24" viewBox="106 48 300 416"')
    .replaceAll('#a5edbd', 'currentColor')
    .replace(/\s*<rect id="background"[^>]*\/>/, ''));
  // Full-size opaque launch images keep iOS from showing a blank launch screen.
  const artwork = source.replace(/<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const background = JSON.parse(fs.readFileSync(path.join(media, 'manifest.webmanifest'), 'utf8')).background_color;
  const startup = path.join(temporary, 'startup.svg');
  for (const image of startupImages) {
    const size = 144 * image.ratio;
    fs.writeFileSync(startup, `<svg xmlns="http://www.w3.org/2000/svg" width="${image.width}" height="${image.height}" viewBox="0 0 ${image.width} ${image.height}"><rect width="100%" height="100%" fill="${background}"/><svg x="${(image.width - size) / 2}" y="${(image.height - size) / 2}" width="${size}" height="${size}" viewBox="0 0 512 512" fill="#a5edbd">${artwork}</svg></svg>`);
    render(startup, path.join(media, image.name), image.width, image.height);
  }
  const html = path.join(media, 'preview.html');
  const links = startupImages.map(image => `  <link rel="apple-touch-startup-image" href="/app/${image.name}" media="${image.media}">`).join('\n');
  fs.writeFileSync(html, fs.readFileSync(html, 'utf8').replace(
    /  <!-- Startup images: generated by npm run icons -->[\s\S]*?  <!-- End startup images -->/,
    `  <!-- Startup images: generated by npm run icons -->\n${links}\n  <!-- End startup images -->`));
  console.log('Generated PNG icons, Activity Bar SVG and iOS startup images from media/icon.svg.');
} catch (error) {
  throw new Error(`Icon rendering failed. Install Inkscape or set INKSCAPE to its executable path. ${error.message}`);
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
